"""Урок od03. Сортировка вставками (insertion sort).

Как игрок сортирует карты: берём элементы по одному и каждый
вставляем на его место в уже отсортированную левую часть, сдвигая
вправо всех, кто больше.

Сложность: O(n²) в худшем случае (вход задом наперёд), но алгоритм
АДАПТИВЕН: чем ближе вход к порядку, тем меньше работы. На уже
отсортированном входе — O(n): n-1 сравнений и ноль сдвигов. Поэтому
вставки живут в продакшене до сих пор (Timsort внутри sorted()
использует их для коротких кусков).

Стабильна: сдвигаются только строго большие, равные не перепрыгиваются.

Каждый сдвиг устраняет ровно одну инверсию, поэтому число сдвигов
равно числу инверсий входа — и совпадает с числом обменов пузырька
(проверяется в compare_sorts.py). Итоговая укладка key в счётчик
сдвигов не входит: перемещение «мешавших» — вся работа алгоритма.
"""

from sort_stats import Stats


def insertion_sort(items):
    """Вернуть (новый отсортированный список, Stats). Вход не меняется."""
    arr = list(items)
    stats = Stats("вставки")
    for i in range(1, len(arr)):  # arr[0] в одиночку уже отсортирован
        key = arr[i]
        j = i - 1
        # «Часовой» j >= 0 стоит ПЕРЕД обращением arr[j]: and ленив,
        # и при j == -1 чтения arr[-1] (последнего элемента!) не будет.
        while j >= 0:
            stats.comparisons += 1
            if arr[j] > key:
                arr[j + 1] = arr[j]  # сдвиг вправо, дырка ползёт влево
                stats.writes += 1
                j -= 1
            else:
                break
        arr[j + 1] = key  # key ложится в дырку
    return arr, stats


if __name__ == "__main__":
    data = [5, 2, 4, 1, 3]
    result, stats = insertion_sort(data)
    print(f"{data} -> {result}")
    print(f"Работа: {stats.summary()}")

    result, stats = insertion_sort([1, 2, 3, 4, 5])
    print(f"\nУже отсортированный вход: {stats.summary()}")
    print("(ноль сдвигов — каждая «карта» сразу на месте: адаптивность)")
