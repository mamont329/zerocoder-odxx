"""Урок od03. Пузырьковая сортировка (bubble sort).

Идём по массиву и сравниваем СОСЕДЕЙ; стоят неправильно — меняем
местами. За один проход самый большой элемент «всплывает» в конец,
как пузырёк воздуха в воде. Повторяем, пока всплывать нечему.

Сложность: O(n²) в среднем и худшем случае. Включены обе классические
оптимизации:
  * укорачивающийся хвост — после k проходов последние k элементов
    уже на местах, сравнивать их снова незачем;
  * флаг «был ли обмен» — проход без обменов означает, что массив
    отсортирован: досрочный выход. Благодаря флагу лучший случай
    (уже отсортированный вход) — O(n), один проход.

Каждый обмен соседей устраняет ровно одну инверсию (пару элементов
не в том порядке), поэтому число обменов пузырька равно числу
инверсий входного массива — проверяется в compare_sorts.py.
"""

from sort_stats import Stats


def bubble_sort(items):
    """Вернуть (новый отсортированный список, Stats). Вход не меняется."""
    arr = list(items)
    stats = Stats("пузырёк")
    for end in range(len(arr) - 1, 0, -1):  # end — граница «неготовой» части
        swapped = False
        for j in range(end):
            stats.comparisons += 1
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
                stats.swaps += 1
                swapped = True
        if not swapped:  # проход без обменов — всё уже стоит по местам
            break
    return arr, stats


if __name__ == "__main__":
    data = [5, 2, 4, 1, 3]
    result, stats = bubble_sort(data)
    print(f"{data} -> {result}")
    print(f"Работа: {stats.summary()}")

    result, stats = bubble_sort([1, 2, 3, 4, 5])
    print(f"\nУже отсортированный вход: {stats.summary()}")
    print("(один проход сравнений и ноль обменов — сработал флаг)")
