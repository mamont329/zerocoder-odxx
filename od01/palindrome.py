"""Урок od01. Проверка, является ли строка палиндромом.

Палиндром — строка, которая читается одинаково слева направо и справа
налево. Проверяем «по-человечески»: регистр букв, пробелы и знаки
препинания не учитываются, поэтому «А роза упала на лапу Азора» — палиндром.
"""

# Пошаговый алгоритм
#
# Этап 1. Нормализация (подготовка строки к сравнению):
#   1. Привести все символы строки к нижнему регистру,
#      чтобы «А» и «а» считались одним и тем же символом.
#   2. Отбросить все символы, кроме букв и цифр
#      (пробелы, запятые, дефисы и т.п. на «палиндромность» не влияют).
#
# Этап 2. Проверка симметрии (метод двух указателей):
#   3. Поставить левый указатель на первый символ строки,
#      правый — на последний.
#   4. Сравнить символы под указателями:
#      - если они РАЗНЫЕ — строка не палиндром, ответ «нет», стоп;
#      - если одинаковые — сдвинуть левый указатель на шаг вправо,
#        правый на шаг влево.
#   5. Повторять шаг 4, пока указатели не встретятся или не разминутся:
#      середина достигнута, ни одного расхождения не найдено —
#      строка палиндром, ответ «да».
#
# До конца строки идти не нужно: достаточно дойти до середины, потому что
# каждое сравнение проверяет сразу ПАРУ символов — левый и его зеркального
# напарника (сравнивать вторую половину со второй половиной бессмысленно).


def normalize(text: str) -> str:
    """Готовит строку к проверке: нижний регистр, только буквы и цифры."""
    return "".join(ch for ch in text.lower() if ch.isalnum())


def is_palindrome_pointers(text: str) -> bool:
    """Реализация 1: два указателя (дословно по алгоритму выше).

    Указатели идут с концов строки навстречу друг другу и сравнивают
    зеркальные пары символов. При первом же несовпадении — досрочный
    выход с ответом False, без просмотра остатка строки.
    """
    s = normalize(text)
    left = 0
    right = len(s) - 1
    while left < right:
        if s[left] != s[right]:
            return False
        left += 1
        right -= 1
    return True


def is_palindrome_reverse(text: str) -> bool:
    """Реализация 2: сравнение с перевёрнутой копией.

    Срез s[::-1] строит новую строку, записанную задом наперёд.
    Палиндром — это строка, совпадающая со своим перевёртышем,
    так что вся проверка укладывается в одно сравнение ==.
    Коротко и по-питоновски, но тратит память на копию строки.
    """
    s = normalize(text)
    return s == s[::-1]


if __name__ == "__main__":
    examples = [
        "шалаш",
        "А роза упала на лапу Азора",
        "Madam, I'm Adam",
        "12321",
        "Аргентина манит негра",
        "просто строка",
        "об",
        "я",
        "",
    ]

    print(f"{'строка':<30} | {'указатели':<9} | {'перевёртыш':<10} | совпали")
    print("-" * 65)
    for text in examples:
        by_pointers = is_palindrome_pointers(text)
        by_reverse = is_palindrome_reverse(text)
        shown = f"«{text}»"
        print(
            f"{shown:<30} | {str(by_pointers):<9} | {str(by_reverse):<10} "
            f"| {'да' if by_pointers == by_reverse else 'НЕТ!'}"
        )
