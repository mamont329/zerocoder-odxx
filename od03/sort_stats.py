"""Урок od03. Stats — счётчики работы алгоритма сортировки.

Секундомер меряет всё скопом (включая накладные расходы Python),
а счётчики показывают чистую работу алгоритма — ровно те величины,
о которых говорит теория сложности.

У каждого алгоритма своя «валюта» перемещений, сравнения — общие:
  comparisons — сравнения пар элементов (все алгоритмы);
  swaps       — обмены двух ячеек (пузырёк, выбор);
  writes      — сдвиги элементов (вставки);
  copies      — копирования элементов в подсписки (быстрая);
  calls       — вызовы рекурсии (быстрая);
  max_depth   — максимальная глубина рекурсии (быстрая).
"""


class Stats:
    """Счётчики одной прогонки сортировки. Каждая сортировка заводит
    свой экземпляр и возвращает его рядом с результатом."""

    FIELDS = [
        ("comparisons", "сравнения"),
        ("swaps", "обмены"),
        ("writes", "сдвиги"),
        ("copies", "копирования"),
        ("calls", "вызовы рекурсии"),
        ("max_depth", "глубина рекурсии"),
    ]

    def __init__(self, name):
        self.name = name
        self.comparisons = 0
        self.swaps = 0
        self.writes = 0
        self.copies = 0
        self.calls = 0
        self.max_depth = 0

    def summary(self):
        """Строка только с ненулевыми счётчиками — для мини-демо."""
        parts = []
        for attr, label in self.FIELDS:
            value = getattr(self, attr)
            if value:
                parts.append(f"{label}: {value}")
        return ", ".join(parts) if parts else "работы не потребовалось"
